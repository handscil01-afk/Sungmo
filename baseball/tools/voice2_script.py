WHO = { 'C': f'캐스터 {CASTER} (1차 녹음 때와 같은 목소리, 같은 Speaker/Voice)', 'A': f'해설위원 {ANALYST} (캐스터와 다른 목소리: 차분한 40대 남성, 낮고 부드러운 톤. 모든 A 묶음은 같은 Speaker/Voice)' }
import os
here = os.path.dirname(os.path.abspath(__file__)); V = os.path.join(here, '..', 'voice')
rows = []
for code, who, tone, lines in B:
    with open(os.path.join(V, 'prompts2', f'{code}.txt'), 'w') as f:
        f.write(HEAD.format(code=code, who=WHO[who], tone=tone))
        for _, t in lines: f.write(t + '\n')
    rows += [(code, i, t) for i, t in lines]
with open(os.path.join(V, 'script2.txt'), 'w') as f:
    for n, (code, i, t) in enumerate(rows, 1): f.write(f'{n:03d}\t{code}\t{i}\t{t}\n')
print(len(B), 'bundles', len(rows), 'lines', [len(l) for _, _, _, l in B])
